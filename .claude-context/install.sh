#   ./.claude-context/install.sh            install (opt-in mode)
#   ./.claude-context/install.sh --uninstall  remove
set -euo pipefail

DEST="${CLAUDE_CONFIG_DIR:-$HOME/.claude}/git-context"

if [ "${1:-}" = "--uninstall" ]; then
  current="$(git config --global --get core.hooksPath || true)"
  if [ "$current" = "$DEST/hooks" ]; then
    prev="$(git config --global --get claudeContext.previousHooksPath || true)"
    if [ -n "$prev" ]; then git config --global core.hooksPath "$prev"
    else git config --global --unset core.hooksPath || true; fi
  fi
  git config --global --unset claudeContext.mode || true
  git config --global --unset claudeContext.previousHooksPath || true
  echo "claude-context: uninstalled (files left in $DEST)"
  exit 0
fi

